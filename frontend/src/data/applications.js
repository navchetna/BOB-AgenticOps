// Application Details, Application Owner Information, Business Owner
// Information, Hosting Environment, Details of Initial Procurement and
// Details of Current ATS. Replace with a real API call once the backend
// exposes one.

function fields(pairs) {
  return pairs.map(([name, value]) => ({ name, value }))
}

// Fields tagged with the team/system that owns filling them — drives the
// source-colored rows, the legend panel, and the agentic-flow demo.
function sourcedFields(triples) {
  return triples.map(([name, value, source]) => ({ name, value, source }))
}

